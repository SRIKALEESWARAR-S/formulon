"""Spec-to-test traceability check (spec-driven development gate).

Fails (exit 1) if a requirement in specs/*.md has no test citing it, or a test cites an
unknown requirement.  ``--write`` regenerates docs/TRACEABILITY.md.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).parents[1]
REQ = re.compile(r"REQ-[A-Z]+-\d{3}")


def main(write: bool = False) -> int:
    specs = {}
    for f in sorted((ROOT / "specs").glob("SPEC-*.md")):
        for line in f.read_text(encoding="utf-8").splitlines():
            m = re.match(r"- \*\*(REQ-[A-Z]+-\d{3})\*\*\s*(.*)", line)
            if m:
                specs[m.group(1)] = (f.name, m.group(2))
    cited = {}
    for t in sorted((ROOT / "tests").glob("test_*.py")):
        for rid in set(REQ.findall(t.read_text(encoding="utf-8"))):
            cited.setdefault(rid, []).append(t.name)
    missing = [r for r in specs if r not in cited]
    unknown = [r for r in cited if r not in specs]
    for r in missing:
        print(f"UNTESTED requirement: {r} ({specs[r][0]})")
    for r in unknown:
        print(f"UNKNOWN requirement cited by {cited[r]}: {r}")
    if write:
        lines = ["# Traceability matrix (generated by scripts/spec_trace.py --write)", "",
                 "| Requirement | Spec file | Tests |", "|---|---|---|"]
        for r, (f, _txt) in specs.items():
            lines.append(f"| {r} | {f} | {', '.join(cited.get(r, ['**NONE**']))} |")
        (ROOT / "docs" / "TRACEABILITY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(specs)} requirements, {len(specs) - len(missing)} traced to tests")
    return 1 if (missing or unknown) else 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
